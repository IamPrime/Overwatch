// Inline SVG icons (Feather-style strokes) rather than an icon font/library dependency for the
// handful the app needs. They inherit the text colour; size them with Tailwind (size-4, size-5...).
function Icon({ children, className = 'size-4', strokeWidth = 2 }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

